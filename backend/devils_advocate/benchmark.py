"""Small inspectable regression benchmark; no LLM or biological superiority claim.

Labels are manually specified below from the displayed registry reason, not
generated by the classifier. Compound applicability is a name/disease check only.
"""
import json
import argparse
from pathlib import Path
from .models import Claim, Investigation
from .evaluation import prepare_evaluation, score
from .stop_reasons import stop_reason_label

# (target, NCT, expected category, potentially relevant linked concern, unsupported outcome inference)
LABELS = [
    ('bace1', 'NCT01739348', 'unknown', False, True),
    ('bace1', 'NCT02783573', 'efficacy', True, False),
    ('bace1', 'NCT02972658', 'other', False, False),  # dependent closure
    ('pcsk9', 'NCT03331666', 'operational', False, False),
    ('egfr', 'NCT02443337', 'efficacy', True, False),
    ('egfr', 'NCT05241873', 'unknown', False, False),  # explicitly not safety-related
    ('egfr', 'NCT06704724', 'operational', False, False),
]

def evidence_summary_baseline(result: Investigation, cases: list[dict]) -> tuple[list[dict], list[dict]]:
    """Extract-only baseline: states fields, abstains on concern/relevance.

    It accepts a nonempty citation as support without looking up its content.
    This intentionally simple baseline is documented, not an executed LLM.
    """
    trials = {t.nct_id: t for t in result.trials}
    summaries, predictions = [], []
    for case in cases:
        if case['type'] == 'trial_outcome':
            trial = trials[case['source_id']]
            summaries.append({'id': case['id'], 'text': f'{trial.status}. Stop reason: {stop_reason_label(trial)}', 'source_url': trial.url})
            unsupported = not bool(trial.why_stopped)
        else:
            summaries.append({'id': case['id'], 'text': case['claim']['text'], 'source_id': case['claim']['source_id']})
            unsupported = not bool(case['claim']['source_id'])
        predictions.append({'id': case['id'], 'concern': 'unknown', 'relevant_failure': False, 'unsupported': unsupported})
    return summaries, predictions

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--refresh-fixture', action='store_true', help='Replace small benchmark extracts using saved live sources')
    args = parser.parse_args()
    root = Path(__file__).parent
    fixture = root / 'fixtures' / 'benchmark_sources.json'
    if args.refresh_fixture:
        sources = {name: Investigation.model_validate_json((root / 'validation' / f'{name}_sources.json').read_text(encoding='utf-8'))
                   for name in ['bace1', 'pcsk9', 'egfr']}
        compact = {}
        for name, source in sources.items():
            wanted = {nct for target, nct, *_ in LABELS if target == name}
            data = source.model_dump(mode='json', exclude={'claims', 'revisions', 'assessments', 'publications'})
            data['trials'] = [t.model_dump(mode='json', exclude={'outcome_records', 'population'}) for t in source.trials if t.nct_id in wanted]
            compact[name] = data
        fixture.write_text(json.dumps(compact, indent=2), encoding='utf-8')
    sources = {name: Investigation.model_validate(data) for name, data in json.loads(fixture.read_text(encoding='utf-8')).items()}
    labels, system, baseline, bundles = [], [], [], []
    for name, nct, category, relevant, unsupported in LABELS:
        source = sources[name]
        trial = next(t for t in source.trials if t.nct_id == nct)
        subset = source.model_copy(update={'trials': [trial], 'publications': [], 'claims': [], 'assessments': []})
        bundle = prepare_evaluation(subset)
        summaries, base = evidence_summary_baseline(subset, bundle['cases'])
        labels.append({'id': nct + ':outcome', 'concern': category, 'relevant_failure': relevant, 'unsupported': unsupported})
        system.extend(bundle.pop('system_predictions'))
        baseline.extend(base)
        # Small frozen source extracts suffice to reproduce this benchmark.
        bundles.append({'cases': bundle['cases'], 'target': source.target.model_dump(),
                        'trial': trial.model_dump(mode='json', exclude={'outcome_records', 'population'}),
                        'baseline_summary': summaries})
    source = sources['bace1']
    trial = next(t for t in source.trials if t.nct_id == 'NCT01739348')
    candidates = [Claim(claim_id='fabricated-target-invalidity', text='The target is invalid.', kind='fact',
                        source_id=trial.nct_id, source_field='why_stopped', excerpt='The target is invalid.', relevance='Adversarial test only; not a biomedical finding.'),
                  Claim(claim_id='documented-status', text=trial.status, kind='fact', source_id=trial.nct_id,
                        source_field='status', excerpt=trial.status, relevance='Registry status only.')]
    subset = source.model_copy(update={'trials': [], 'claims': [], 'publications': []})
    # Include the source for claim verification but remove the extra trial-outcome case.
    subset.trials = [trial]
    bundle = prepare_evaluation(subset, candidates)
    claim_cases = [c for c in bundle['cases'] if c['type'] == 'claim_support']
    summaries, base = evidence_summary_baseline(subset, claim_cases)
    system.extend(p for p in bundle['system_predictions'] if p['id'].endswith(':support'))
    baseline.extend(base)
    for c, unsupported in zip(candidates, [True, False]):
        labels.append({'id': c.claim_id + ':support', 'concern': 'unknown', 'relevant_failure': False, 'unsupported': unsupported})
    bundles.append({'cases': claim_cases, 'trial': trial.model_dump(mode='json', exclude={'outcome_records', 'population'}), 'baseline_summary': summaries})
    report = {'description': 'Nine manually inspectable registry/claim regression cases; not an independent clinical benchmark or LLM comparison.',
              'pipeline': score(labels, system), 'extract_only_summary_baseline': score(labels, baseline),
              'labels': labels, 'pipeline_predictions': system, 'baseline_predictions': baseline, 'shared_source_cases': bundles}
    output = root / 'validation' / 'benchmark_report.json'
    output.write_text(json.dumps(report, indent=2), encoding='utf-8')
    print(json.dumps({k: v for k, v in report.items() if k in ['description', 'pipeline', 'extract_only_summary_baseline']}, indent=2))

if __name__ == '__main__':
    main()
